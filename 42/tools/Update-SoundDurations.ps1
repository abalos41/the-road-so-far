param(
    [string]$Mod42Directory
)

# Measures the length of every sound referenced by the mod's sound scripts and
# writes media\lua\shared\TheRoadSoFarFM\Sync\Durations.lua. The multiplayer
# server uses these lengths as a station/cassette clock. Re-run after adding,
# removing or replacing any audio file.

$ErrorActionPreference = "Stop"

if (-not $Mod42Directory) {
    $Mod42Directory = Split-Path -Parent $PSScriptRoot
}
$mod42Directory = [System.IO.Path]::GetFullPath($Mod42Directory)
$scriptDirectory = Join-Path $mod42Directory "media\scripts"
$outputPath = Join-Path $mod42Directory "media\lua\shared\TheRoadSoFarFM\Sync\Durations.lua"
$soundScripts = @("Radio_Sounds.txt", "Cassette_Sounds.txt", "Sync_Sounds.txt")

function Get-OggDurationMs {
    param([byte[]]$Bytes)

    $segments = $Bytes[26]
    $packet = 27 + $segments
    $rate = 0
    $preSkip = 0
    if ($Bytes[$packet] -eq 1 -and [System.Text.Encoding]::ASCII.GetString($Bytes, $packet + 1, 6) -eq "vorbis") {
        $rate = [BitConverter]::ToUInt32($Bytes, $packet + 12)
    }
    elseif ([System.Text.Encoding]::ASCII.GetString($Bytes, $packet, 8) -eq "OpusHead") {
        $rate = 48000
        $preSkip = [BitConverter]::ToUInt16($Bytes, $packet + 10)
    }
    if ($rate -le 0) {
        throw "Unsupported OGG stream."
    }

    for ($i = $Bytes.Length - 14; $i -ge 0; $i--) {
        if ($Bytes[$i] -eq 0x4F -and $Bytes[$i + 1] -eq 0x67 -and $Bytes[$i + 2] -eq 0x67 -and $Bytes[$i + 3] -eq 0x53) {
            $granule = [BitConverter]::ToInt64($Bytes, $i + 6)
            return [int][math]::Round((($granule - $preSkip) * 1000.0) / $rate)
        }
    }
    throw "No OGG page found."
}

function Get-SoundFileDurationMs {
    param([string]$Path)

    $bytes = [System.IO.File]::ReadAllBytes($Path)
    if ([System.IO.Path]::GetExtension($Path).ToLowerInvariant() -ne ".ogg") {
        throw "Unsupported audio format (only .ogg is supported): $Path"
    }
    return Get-OggDurationMs $bytes
}

try {
    $entries = [System.Collections.Generic.List[string]]::new()
    foreach ($scriptName in $soundScripts) {
        $scriptPath = Join-Path $scriptDirectory $scriptName
        if (-not (Test-Path -LiteralPath $scriptPath)) {
            continue
        }

        $currentSound = $null
        foreach ($line in Get-Content -LiteralPath $scriptPath) {
            if ($line -match '^\s*sound\s+(\S+)\s*$') {
                $currentSound = $Matches[1]
            }
            elseif ($currentSound -and $line -match '^\s*file\s*=\s*(.+?)\s*,?\s*$') {
                $relativePath = $Matches[1].Replace('/', '\')
                $audioPath = Join-Path $mod42Directory $relativePath
                if (-not (Test-Path -LiteralPath $audioPath)) {
                    Write-Warning "$currentSound : missing file $relativePath"
                }
                else {
                    $durationMs = Get-SoundFileDurationMs $audioPath
                    $entries.Add("    $currentSound = $durationMs,")
                }
                $currentSound = $null
            }
        }
    }

    New-Item -ItemType Directory -Path (Split-Path -Parent $outputPath) -Force | Out-Null
    $content = "-- Generated by tools\Update-SoundDurations.ps1. Values are milliseconds.`r`n" +
        "TheRoadSoFarFMDurations = {`r`n" + ($entries -join "`r`n") + "`r`n}`r`n"
    [System.IO.File]::WriteAllText($outputPath, $content, (New-Object System.Text.UTF8Encoding($false)))

    Write-Host ""
    Write-Host "Measured $($entries.Count) sounds."
    Write-Host "Durations written to $outputPath"
}
catch {
    Write-Error $_
    exit 1
}
